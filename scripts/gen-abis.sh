#!/usr/bin/env bash
# Regenerates packages/core/src/abis.ts from the Foundry build output.
set -euo pipefail
cd "$(dirname "$0")/../contracts"
export PATH="$PATH:$HOME/.foundry/bin"
forge build >/dev/null
out=../packages/core/src/abis.ts
echo "// AUTO-GENERATED by scripts/gen-abis.sh — do not edit" > $out
for c in Flatland Standing WifGate ParticipationVault BasketVault WifBuyback DepositBox FlatAccount FlatAccountFactory FlatPaymaster; do
  f=$(find out -name "$c.json" | head -1)
  printf 'export const %sAbi = ' "$(echo ${c:0:1} | tr A-Z a-z)${c:1}" >> $out
  python3 -c "import json,sys;sys.stdout.write(json.dumps(json.load(open('$f'))['abi']))" >> $out
  echo " as const;" >> $out
done
cat >> $out <<'EOF'
export const erc20Abi = [
  {"type":"function","name":"balanceOf","stateMutability":"view","inputs":[{"name":"a","type":"address"}],"outputs":[{"type":"uint256"}]},
  {"type":"function","name":"allowance","stateMutability":"view","inputs":[{"name":"o","type":"address"},{"name":"s","type":"address"}],"outputs":[{"type":"uint256"}]},
  {"type":"function","name":"approve","stateMutability":"nonpayable","inputs":[{"name":"s","type":"address"},{"name":"v","type":"uint256"}],"outputs":[{"type":"bool"}]},
  {"type":"function","name":"transfer","stateMutability":"nonpayable","inputs":[{"name":"to","type":"address"},{"name":"v","type":"uint256"}],"outputs":[{"type":"bool"}]},
  {"type":"function","name":"totalSupply","stateMutability":"view","inputs":[],"outputs":[{"type":"uint256"}]},
  {"type":"function","name":"decimals","stateMutability":"view","inputs":[],"outputs":[{"type":"uint8"}]},
  {"type":"event","name":"Transfer","inputs":[{"name":"from","type":"address","indexed":true},{"name":"to","type":"address","indexed":true},{"name":"value","type":"uint256","indexed":false}]}
] as const;
EOF
echo "wrote $out"

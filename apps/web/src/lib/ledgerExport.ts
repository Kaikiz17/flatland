/** CSV, printable HTML, and client-side PNG export of the Sign creator ledger. */

export const KIND_LABELS = ['Petition', 'RSVP', 'Allowlist', 'Access'] as const;
export const LEDGER_WARN = "Don't share this publicly. Share it privately for verification only.";

export type LedgerRow = { no: number; wallet: string; name?: string; ens?: string; ts?: number; block?: number; tx?: string; passId: string; detail?: string };
export type LedgerList = {
  kind: string; id: string; title: string; signKind: number; creator: string; contract: string;
  created?: number; total: number; count: number; burnedWif: number; exportedAt: number; rows: LedgerRow[];
};

export const lagosStamp = (ts?: number, withTime = true) => {
  if (!ts) return '—';
  const opts: Intl.DateTimeFormatOptions = { timeZone: 'Africa/Lagos', day: 'numeric', month: 'short', year: 'numeric', ...(withTime ? { hour: '2-digit', minute: '2-digit', hour12: false } : {}) };
  return new Intl.DateTimeFormat('en-GB', opts).format(new Date(ts * 1000));
};

export const rowName = (r: LedgerRow) => r.ens || r.name || '—';

export const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
const csvCell = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);

export function ledgerCsv(list: LedgerList, rows: LedgerRow[]): string {
  return [
    ['No.', 'Name', 'Wallet address', 'Pass ID', 'Time (Lagos UTC+1)', 'Tx'].join(','),
    ...rows.map((r) => [r.no, csvCell(rowName(r)), r.wallet, r.passId, lagosStamp(r.ts) + ' Lagos', r.tx ?? ''].join(',')),
  ].join('\n');
}


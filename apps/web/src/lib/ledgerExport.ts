const W = 1600;
const PAD = 72;
const ROW_H = 46;
const THEAD_H = 42;
const FOOTER_H = 86;
const PAGE_MAX = 2400;
const TALL_MAX = 5600;
const INK = '#1a1208';
const GOLD = '#f2b705';
const PAPER = '#fffaf0';
const CREAM = '#f3ead6';
const ZEBRA = '#f7f0e2';
const ORANGE = '#ff5a36';
const MUTED = '#8a6a10';
const LINE = '#e6d8b8';

function headerHeight(titleLines: number) {
  return PAD + 28 + titleLines * 44 + 18 + 168 + 20;
}

function wrapText(ctx: CanvasRenderingContext2D, text: string, maxW: number): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    const next = cur ? `${cur} ${w}` : w;
    if (ctx.measureText(next).width <= maxW) cur = next;
    else { if (cur) lines.push(cur); cur = w; }
  }
  if (cur) lines.push(cur);
  return lines.length ? lines : [text];
}

function pill(ctx: CanvasRenderingContext2D, x: number, y: number, label: string) {
  ctx.save();
  ctx.font = '800 13px Montserrat, system-ui, sans-serif';
  const w = ctx.measureText(label).width + 24;
  const h = 26, r = 13;
  ctx.fillStyle = ORANGE;
  ctx.beginPath();
  ctx.moveTo(x + r, y); ctx.arcTo(x + w, y, x + w, y + h, r); ctx.arcTo(x + w, y + h, x, y + h, r); ctx.arcTo(x, y + h, x, y, r); ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath(); ctx.fill();
  ctx.fillStyle = PAPER;
  ctx.textBaseline = 'middle';
  ctx.fillText(label, x + 12, y + h / 2 + 0.5);
  ctx.restore();
  return w;
}

function drawPage(list: LedgerList, rows: LedgerRow[], page: number, pages: number, height: number, titleLines: string[]): HTMLCanvasElement {
  const c = document.createElement('canvas');
  c.width = W; c.height = height;
  const ctx = c.getContext('2d');
  if (!ctx) throw new Error('canvas');
  ctx.fillStyle = PAPER;
  ctx.fillRect(0, 0, W, height);
  ctx.strokeStyle = INK;
  ctx.lineWidth = 16;
  ctx.strokeRect(8, 8, W - 16, height - 16);
  ctx.strokeStyle = GOLD;
  ctx.lineWidth = 4;
  ctx.strokeRect(20, 20, W - 40, height - 40);

  let y = PAD;
  ctx.fillStyle = MUTED;
  ctx.font = '800 13px Montserrat, system-ui, sans-serif';
  ctx.letterSpacing = '6px';
  ctx.fillText('FLATLAND  ·  SIGN  ·  PRIVATE LEDGER', PAD, y);
  ctx.letterSpacing = '0px';
  y += 36;

  ctx.fillStyle = INK;
  ctx.font = '700 36px Georgia, "Times New Roman", serif';
  for (const line of titleLines) { ctx.fillText(line, PAD, y); y += 44; }
  const kind = (KIND_LABELS[list.signKind] ?? 'Sign').toUpperCase();
  const last = titleLines[titleLines.length - 1] ?? '';
  ctx.font = '700 36px Georgia, "Times New Roman", serif';
  pill(ctx, PAD + ctx.measureText(last).width + 16, y - 44 - 22, kind);
  y += 8;

  const infoH = 168;
  ctx.fillStyle = CREAM;
  ctx.fillRect(PAD, y, W - PAD * 2, infoH);
  ctx.fillStyle = GOLD;
  ctx.fillRect(PAD, y, 6, infoH);
  const info = [
    ['CREATOR', list.creator],
    ['CONTRACT / GATE', `${list.contract}  ·  #${list.id}`],
    ['CREATED', `${lagosStamp(list.created)} Lagos (UTC+1)`],
    ['TOTAL SIGNERS', String(list.total)],
    ['$WIF BURNED', String(list.burnedWif)],
    ['EXPORT TIME', `${lagosStamp(list.exportedAt)} Lagos (UTC+1)`],
  ];
  const colW = (W - PAD * 2 - 28) / 2;
  info.forEach((pair, i) => {
    const ix = PAD + 20 + (i % 2) * colW;
    const iy = y + 18 + Math.floor(i / 2) * 50;
    ctx.fillStyle = MUTED;
    ctx.font = '700 11px Montserrat, system-ui, sans-serif';
    ctx.letterSpacing = '1.4px';
    ctx.fillText(pair[0], ix, iy);
    ctx.letterSpacing = '0px';
    ctx.fillStyle = INK;
    ctx.font = i < 2 ? '500 14px ui-monospace, "DM Mono", monospace' : '500 15px Montserrat, system-ui, sans-serif';
    ctx.fillText(pair[1], ix, iy + 20);
  });
  y += infoH + 24;

  const cols = [
    { key: 'no', label: 'NO.', x: PAD, w: 70 },
    { key: 'name', label: 'NAME', x: PAD + 70, w: 220 },
    { key: 'wallet', label: 'WALLET ADDRESS', x: PAD + 290, w: 500 },
    { key: 'pass', label: 'PASS ID', x: PAD + 790, w: 310 },
    { key: 'time', label: 'TIME (LAGOS / UTC+1)', x: PAD + 1100, w: W - PAD * 2 - 1100 },
  ];
  ctx.fillStyle = MUTED;
  ctx.font = '700 11px Montserrat, system-ui, sans-serif';
  ctx.letterSpacing = '1.4px';
  cols.forEach((col) => ctx.fillText(col.label, col.x, y + 18));
  ctx.letterSpacing = '0px';
  ctx.strokeStyle = INK;
  ctx.lineWidth = 2;
  ctx.beginPath(); ctx.moveTo(PAD, y + THEAD_H - 4); ctx.lineTo(W - PAD, y + THEAD_H - 4); ctx.stroke();
  y += THEAD_H;

  rows.forEach((r, i) => {
    if (i % 2 === 1) {
      ctx.fillStyle = ZEBRA;
      ctx.fillRect(PAD, y, W - PAD * 2, ROW_H);
    }
    ctx.strokeStyle = LINE;
    ctx.lineWidth = 1;
    ctx.beginPath(); ctx.moveTo(PAD, y + ROW_H - 0.5); ctx.lineTo(W - PAD, y + ROW_H - 0.5); ctx.stroke();
    ctx.fillStyle = INK;
    ctx.textBaseline = 'middle';
    const mid = y + ROW_H / 2;
    ctx.font = '500 15px ui-monospace, "DM Mono", monospace';
    ctx.fillText(String(r.no), cols[0].x, mid);
    ctx.font = '500 16px Georgia, "Times New Roman", serif';
    ctx.fillText(rowName(r), cols[1].x, mid);
    ctx.font = '500 14px ui-monospace, "DM Mono", monospace';
    ctx.fillText(r.wallet, cols[2].x, mid);
    ctx.fillText(r.passId, cols[3].x, mid);
    ctx.font = '500 14px Montserrat, system-ui, sans-serif';
    ctx.fillText(`${lagosStamp(r.ts)} Lagos`, cols[4].x, mid);
    ctx.textBaseline = 'alphabetic';
    y += ROW_H;
  });

  y = height - FOOTER_H + 18;
  ctx.fillStyle = '#6a5a40';
  ctx.font = '500 13px Montserrat, system-ui, sans-serif';
  ctx.fillText(LEDGER_WARN, PAD, y);
  const pageBit = pages > 1 ? `  ·  Page ${page} of ${pages}` : '';
  ctx.fillText(`Generated by Flatland. Unaudited beta.${pageBit}`, PAD, y + 22);
  return c;
}

/** One tall PNG if the list is short enough; otherwise one PNG per page (header + info repeated). */
export async function ledgerPngs(list: LedgerList, rows: LedgerRow[]): Promise<{ name: string; blob: Blob }[]> {
  const probe = document.createElement('canvas').getContext('2d');
  if (!probe) throw new Error('canvas');
  probe.font = '700 36px Georgia, "Times New Roman", serif';
  const kind = (KIND_LABELS[list.signKind] ?? 'Sign').toUpperCase();
  probe.font = '800 13px Montserrat, system-ui, sans-serif';
  const badgeW = probe.measureText(kind).width + 24 + 20;
  probe.font = '700 36px Georgia, "Times New Roman", serif';
  const titleLines = wrapText(probe, list.title, W - PAD * 2 - badgeW);
  const head = headerHeight(titleLines.length);
  const body = Math.max(rows.length, 1) * ROW_H;
  const totalH = head + body + FOOTER_H + 8;
  const pages: { slice: LedgerRow[]; height: number }[] = [];
  if (totalH <= TALL_MAX) {
    pages.push({ slice: rows, height: Math.max(totalH, 1100) });
  } else {
    const per = Math.max(1, Math.floor((PAGE_MAX - head - FOOTER_H) / ROW_H));
    for (let i = 0; i < rows.length; i += per) {
      const slice = rows.slice(i, i + per);
      pages.push({ slice, height: head + slice.length * ROW_H + FOOTER_H + 8 });
    }
  }
  const out: { name: string; blob: Blob }[] = [];
  for (let i = 0; i < pages.length; i++) {
    const canvas = drawPage(list, pages[i].slice, i + 1, pages.length, pages[i].height, titleLines);
    const blob = await new Promise<Blob>((res, rej) => canvas.toBlob((b) => (b ? res(b) : rej(new Error('png'))), 'image/png'));
    const suffix = pages.length === 1 ? '' : `-${i + 1}`;
    out.push({ name: `flatland-sign-${list.id}-passes${suffix}.png`, blob });
  }
  return out;
}

export function downloadBlob(name: string, blob: Blob) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 2000);
}

export async function downloadLedgerPngs(list: LedgerList, rows: LedgerRow[]) {
  const files = await ledgerPngs(list, rows);
  for (let i = 0; i < files.length; i++) {
    downloadBlob(files[i].name, files[i].blob);
    if (i < files.length - 1) await new Promise((r) => setTimeout(r, 400));
  }
  return files.length;
}

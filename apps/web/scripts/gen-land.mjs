// Generates src/land.ts: equirectangular SVG path of the world's land (Natural Earth 110m via world-atlas) in a 360x180 box.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json')));
const land = feature(topo, topo.objects.land);
const f = (n) => (Math.round(n * 10) / 10).toString();
let d = '';
const polys = land.type === 'FeatureCollection' ? land.features.flatMap((x) => x.geometry.type === 'MultiPolygon' ? x.geometry.coordinates : [x.geometry.coordinates]) : land.geometry.type === 'MultiPolygon' ? land.geometry.coordinates : [land.geometry.coordinates];
for (const poly of polys) for (const ring of poly) {
  ring.forEach(([lon, lat], i) => { d += (i ? 'L' : 'M') + f(lon + 180) + ' ' + f(90 - lat); });
  d += 'Z';
}
writeFileSync(new URL('../src/land.ts', import.meta.url), `// generated by scripts/gen-land.mjs — Natural Earth 110m land, equirectangular, viewBox 0 0 360 180\nexport const LAND_PATH = '${d}';\n`);
console.log('land path bytes', d.length);

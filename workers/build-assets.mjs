// Embeds apps/web/dist into the web worker (generated, git-ignored): workers/web/assets/*.txt + workers/web/assets.gen.ts
// Why embedded: the Workers Assets upload API needs a session JWT sent as a bearer token, which the Cloudflare connector sandbox cannot send
// (it answers 401), so static files are served by the Worker itself. With wrangler you can use [assets] instead (see workers/web/wrangler.toml).
import { readFileSync, readdirSync, statSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join, extname, relative } from 'node:path';
import { createHash } from 'node:crypto';
const root = new URL('..', import.meta.url).pathname;
const dist = join(root, 'apps/web/dist');
const out = join(root, 'workers/web/assets');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png' };
const files = [];
const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); statSync(p).isDirectory() ? walk(p) : files.push(p); } };
walk(dist);
let imports = '', table = '';
files.filter((p) => !p.endsWith('_headers')).forEach((p, i) => {
  const rel = '/' + relative(dist, p);
  if (!MIME[extname(p)]) throw new Error('unknown type ' + rel);
  const bin = extname(p) === '.png';
  writeFileSync(join(out, `${i}.txt`), bin ? readFileSync(p).toString('base64') : readFileSync(p));
  const etag = createHash('sha256').update(readFileSync(p)).digest('hex').slice(0, 16);
  imports += `import a${i} from './assets/${i}.txt';\n`;
  table += `  ${JSON.stringify(rel)}: { body: a${i}, type: ${JSON.stringify(MIME[extname(p)])}, etag: ${JSON.stringify(etag)}${bin ? ', bin: true' : ''} },\n`;
});
writeFileSync(join(root, 'workers/web/assets.gen.ts'), `// GENERATED by workers/build-assets.mjs, do not edit\n${imports}export const STATIC: Record<string, { body: string; type: string; etag: string; bin?: boolean }> = {\n${table}};\n`);
console.log('embedded', files.length - 1, 'files');
